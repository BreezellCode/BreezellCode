#!/usr/bin/env node
// Writes engine/src/zh/doublePinyinSchemes.ts: the spelling algebra of rime-ice's double pinyin
// schemes (GPL-3.0, https://github.com/iDvel/rime-ice), so the engine spells each scheme exactly
// as Rime does.
//
//   gen_double_pinyin.mjs <rime-ice dir>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ice = process.argv[2];
const SCHEMES = {
	ziranma: ['double_pinyin', '自然码'], abc: ['double_pinyin_abc', '智能 ABC'], flypy: ['double_pinyin_flypy', '小鹤'],
	jiajia: ['double_pinyin_jiajia', '拼音加加'], mspy: ['double_pinyin_mspy', '微软'], sogou: ['double_pinyin_sogou', '搜狗'],
	ziguang: ['double_pinyin_ziguang', '紫光'],
};
const out = [];
for (const [id, [file, name]] of Object.entries(SCHEMES)) {
	const lines = readFileSync(join(ice, `${file}.schema.yaml`), 'utf8').split('\n');
	const start = lines.findIndex((l, i) => /^\s+algebra:/.test(l) && lines.slice(0, i).some(x => /^speller:/.test(x)));
	const rules = [];
	for (const l of lines.slice(start + 1)) {
		const m = /^\s+- (.+?)\s*$/.exec(l);
		if (m) { rules.push(m[1].replace(/^'(.*)'$/, '$1')); continue; }
		if (/^\s+#/.test(l) || !l.trim()) continue;
		break;
	}
	out.push(`\t${id}: { name: ${JSON.stringify(name)}, algebra: [\n${rules.map(r => `\t\t${JSON.stringify(r)},`).join('\n')}\n\t] },`);
}
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(join(root, 'engine/src/zh/doublePinyinSchemes.ts'), `// Generated by tools/gen_double_pinyin.mjs from rime-ice (GPL-3.0): the speller algebra of its
// double pinyin schemes. Do not edit by hand.
export const DOUBLE_PINYIN_SCHEMES: Readonly<Record<string, { readonly name: string; readonly algebra: readonly string[] }>> = {
${out.join('\n')}
};
`);
console.error(`${Object.keys(SCHEMES).length} schemes`);
