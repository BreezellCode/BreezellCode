#!/usr/bin/env python3
"""
The Latin words people write among Chinese, and how often: what a Chinese input method should offer
when the letters typed spell one. English text is the wrong measure for this: "my" is common in
English and rare among Chinese, "API" the other way round.

Counts come from lines holding Chinese characters, per source, and each source counts the same in
the end (share of its Latin words), so one long technical manual does not outweigh everything said.
A word's written form is the one most used when it clearly is the word's own (API, GitHub, Python);
a capital that titles or a sentence start gave a common word goes (My, AT: my, at), which the English
word list tells. Also prints how often a word after Chinese text is Latin in each source (the prior).

  build_latin_words.py --english en-words.tsv --out src/latinWords.ts [--min 5] [--max 40000] <source.txt> ...
"""
import argparse
import collections
import re
import sys

# Seen this often in English text, an all-capitals form is a title or a heading.
COMMON_ENGLISH = 1000
HAN = re.compile(r'[㐀-鿿]')
WORD = re.compile(r"(?<![A-Za-z0-9_.\-/\\@#$%&=+:~'])[A-Za-z][A-Za-z]+(?![A-Za-z0-9_\-/\\@=(])")
BEFORE_WORD = re.compile(r'[㐀-鿿]\s?([A-Za-z][A-Za-z]+)(?![A-Za-z0-9_])')
HAN_WORD = re.compile(r'[㐀-鿿]')


def written_form(word: str, forms: collections.Counter, english: dict) -> str:
	top, top_n = forms.most_common(1)[0]
	share = top_n / sum(forms.values())
	if top == word:
		return word
	if top[1:] != top[1:].lower() and top != top.upper():
		return top if share >= 0.6 else word  # capitals inside: GitHub, JavaScript
	common = english.get(word, 0)
	if top == top.upper():
		return top if share >= 0.9 or (share >= 0.6 and common < COMMON_ENGLISH) else word  # API, DNA, OK; not AT, CAN
	return top if share >= 0.9 else word  # Python, Kubernetes; not My, Hello


def main() -> None:
	p = argparse.ArgumentParser()
	p.add_argument('--out', required=True)
	p.add_argument('--english', required=True)
	p.add_argument('--min', type=int, default=5)
	p.add_argument('--max', type=int, default=40000)
	p.add_argument('sources', nargs='+')
	a = p.parse_args()
	english = {}
	with open(a.english, encoding='utf8') as h:
		for line in h:
			w, _, c = line.strip().partition('\t')
			english[w] = int(c or 0)
	shares: collections.Counter[str] = collections.Counter()
	forms: dict[str, collections.Counter[str]] = collections.defaultdict(collections.Counter)
	for path in a.sources:
		counts: collections.Counter[str] = collections.Counter()
		after_han = han = 0
		with open(path, encoding='utf8', errors='replace') as h:
			for line in h:
				if not HAN.search(line):
					continue
				han += len(HAN_WORD.findall(line))
				after_han += len(BEFORE_WORD.findall(line))
				for w in WORD.findall(line):
					if 2 <= len(w) <= 32:
						low = w.lower()
						counts[low] += 1
						forms[low][w] += 1
		total = sum(counts.values()) or 1
		for w, c in counts.items():
			if c >= 2:
				shares[w] += c / total
		print(f'{path}: {total} Latin words, {after_han} right after Chinese, {han} Chinese characters ({after_han / max(1, han):.5f} per character)', file=sys.stderr)
	# Whole counts per million, shares averaged over the sources.
	n = len(a.sources)
	rows = []
	for w, s in shares.most_common():
		ppm = s / n * 1e6
		if sum(forms[w].values()) < a.min or ppm < 0.5:
			continue
		rows.append((written_form(w, forms[w], english), round(ppm, 1)))
		if len(rows) >= a.max:
			break
	body = '\n'.join(f'{w}\t{c:g}' for w, c in rows)
	with open(a.out, 'w', encoding='utf8') as h:
		h.write('/**\n * Latin words written among Chinese, as written, with parts per million of such words.\n * Generated by tools/build_latin_words.py from the same text as the Chinese language model.\n */\n')
		h.write('export const LATIN_WORDS = `' + body + '`;\n')
	print(f'{len(rows)} words, {len(body) // 1024} KB; first: {rows[:12]}', file=sys.stderr)


main()
